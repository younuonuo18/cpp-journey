// sum.c · 1.5 练习：两个整数求和 —— 第二版（迭代版）
//
// 需求分析（第一步的产出）：
//   输入：交互输入两个数字
//   输出：两数相加所得的和
//   边界：正数范围内
//
// 第二版相对第一版多了三件事（都来自"迭代"那条提示词）：
//   1. 输入校验   —— 判断 scanf 的返回值，挡住非数字输入
//   2. 边界校验   —— 只接受正整数（兑现需求里"正数范围内"这句话）
//   3. 溢出检查   —— 两数之和超过 int 上限时提前拦住，而不是静默给出负数
//
// 第一版的实测行为（对比用）：负数照算（-2+7=5）；2147483647+1 输出 -2147483648；
// 输入 abc 时 scanf 失败、变量未初始化，输出垃圾值 -1717986920。

#define _CRT_SECURE_NO_WARNINGS   // VS 默认开 SDL 检查，会把标准 C 的 scanf 当错误（C4996）

#include <stdio.h>
#include <limits.h>               // 为了用 INT_MAX

int main(void)
{
    int a = 0, b = 0;             // 先初始化：这样即使 scanf 失败也不会出现"垃圾值"

    printf("请输入第一个正整数：");
    if (scanf("%d", &a) != 1) {   // scanf 返回成功读入的项数，不是 1 就说明输入的不是整数
        printf("输入无效：请输入整数。\n");
        return 1;                 // 用非 0 退出码表示"这次没算成功"
    }

    printf("请输入第二个正整数：");
    if (scanf("%d", &b) != 1) {
        printf("输入无效：请输入整数。\n");
        return 1;
    }

    // 边界校验：需求里写明"正数范围内"，这一版把它变成真正的约束
    if (a <= 0 || b <= 0) {
        printf("输入无效：本程序只接受正整数，收到 %d 和 %d。\n", a, b);
        return 1;
    }

    // 溢出检查：a + b 会超出 int 上限时提前拦住
    // 因为 b 已经确认是正数，所以 INT_MAX - b 这一步自己是安全的，不会先溢出
    if (a > INT_MAX - b) {
        printf("两数之和超出 int 范围（%d + %d），无法用 int 表示。\n", a, b);
        return 1;
    }

    printf("两数之和：%d\n", a + b);

    return 0;
}
